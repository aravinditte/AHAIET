@router.get("/models")
def models(request: Request):
    s = _settings(request)
    manifest = load_models_manifest(s)
    enriched = []
    for entry in manifest.get("models", []):
        item = dict(entry)
        if entry.get("kind") == "translation":
            # Live artifact state, derived from the disk and the model
            # card — the manifest alone never proves readiness.
            item.update(model_artifacts.resolve_entry(entry).summary())
        if entry.get("kind") == "ocr" and entry.get("engine") == "kraken":
            item["checkpoints_on_disk"] = script_profiles.kraken_checkpoints(
                s, entry.get("script_profile"))
        enriched.append(item)
    return {**manifest, "models": enriched}

@router.post("/uploads")
async def upload(request: Request, file: UploadFile = File(...)):
    s = _settings(request)
    data = await file.read()
    meta = validate_and_decode(data, s)
    s.storage_dir.mkdir(parents=True, exist_ok=True)
    dest = s.storage_dir / f"{meta['sha256']}{meta['extension']}"
    if dest.exists():
        # Existing file with the same content-hash name: verify it is
        # really the same content before trusting it (AHAIET-044).
        import hashlib as _hashlib
        if dest.stat().st_size != len(data) or _hashlib.sha256(dest.read_bytes()).hexdigest() != meta["sha256"]:
            raise AppError(409, "upload_store_conflict",
                           "A stored file with this content id exists but does not match "
                           "the uploaded bytes; it was not overwritten.")
    else:
        # Atomic write: private temp file in the same directory, fsync,
        # then os.replace — an interrupted write can never leave a
        # truncated file under a valid content-hash name, and
        # concurrent identical uploads are safe.
        fd, tmp_name = tempfile.mkstemp(dir=s.storage_dir, prefix=".upload-", suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp_name, dest)
        except BaseException:
            try:
                os.unlink(tmp_name)
            except OSError:
                pass
            raise
    return {"id": meta["sha256"], "format": meta["format"], "width": meta["width"], "height": meta["height"],
            "size_bytes": meta["size_bytes"], "sha256": meta["sha256"]}

