def _require_access(request: Request) -> None:
    """AHAIET-045: when AHAIET_ACCESS_TOKEN is configured, upload reads
    and history require the X-AHAIET-Access-Token header. Unset means
    local single-operator mode (the documented default posture is a
    loopback bind; a content-hash upload id is a locator, not an
    authorization credential — see docs/SECURITY.md)."""
    s = _settings(request)
    if s.access_token:
        supplied = request.headers.get("x-ahaiet-access-token")
        if supplied != s.access_token:
            raise AppError(401, "access_token_required",
                           "This backend requires the X-AHAIET-Access-Token header "
                           "for this endpoint (AHAIET_ACCESS_TOKEN is configured).")

def _find_upload(settings: Settings, upload_id: str) -> Path:
    # upload_id is a sha256 hex string generated by us; reject anything else (traversal-safe).
    if not upload_id or any(c not in "0123456789abcdef" for c in upload_id) or len(upload_id) != 64:
        raise AppError(404, "upload_not_found", f"No upload with id '{upload_id}'.")
    matches = list(settings.storage_dir.glob(upload_id + ".*"))
    if not matches:
        raise AppError(404, "upload_not_found", f"No upload with id '{upload_id}'.")
    return matches[0]

