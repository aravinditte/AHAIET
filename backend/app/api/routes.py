def _last_sweep(s: Settings) -> dict | None:
    """Most recent maintenance run record (AHAIET-016/017)."""
    if not s.db_path.exists():
        return None
    try:
        conn = store.connect(s.db_path)
        try:
            row = conn.execute(
                "SELECT created_at, kind, dry_run, status, error FROM maintenance_runs "
                "ORDER BY id DESC LIMIT 1").fetchone()
        finally:
            conn.close()
    except Exception:
        return None
    return dict(row) if row else None

def _provisioning_state(s: Settings, ocr: dict, corpus: dict, any_model: bool) -> dict:
    """The provisioning state machine summary (AHAIET-056), computed
    from real checks only — see docs/PROVISIONING.md for the states
    and the verification command for each transition."""
    tess = ocr.get("tesseract", {})
    states = {
        "binary_present": bool(tess.get("binary_available")),
        "traineddata_verified": bool(tess.get("language_data_available")),
        "corpus_imported": corpus.get("status") == "available",
        "model_trained": bool(any_model),
        "model_evaluated": any(
            e.get("evaluation_state") == "evaluated"
            for p in model_selection.per_profile_readiness(s, {}).values()
            for e in p.get("engines", [])),
    }
    reached = "not_installed"
    for name in ("binary_present", "traineddata_verified", "corpus_imported",
                 "model_trained", "model_evaluated"):
        if states[name]:
            reached = name
        else:
            break
    return {"state": reached, "checks": states,
            "note": "offline_benchmark_passed is recorded only by a real offline "
                    "benchmark run (docs/PROVISIONING.md); it is never inferred."}

