@router.get("/models")
def models(request: Request):
    s = _settings(request)
    manifest = load_models_manifest(s)
    enriched = []
    for entry in manifest.get("models", []):
        item = dict(entry)
        if entry.get("kind") == "translation":
            # Live artifact state, derived from the disk and the model
            # card — the manifest alone never proves readiness.
            item.update(model_artifacts.resolve_entry(entry).summary())
        if entry.get("kind") == "ocr" and entry.get("engine") == "kraken":
            item["checkpoints_on_disk"] = script_profiles.kraken_checkpoints(
                s, entry.get("script_profile"))
        enriched.append(item)
    return {**manifest, "models": enriched}

@router.post("/uploads")
async def upload(request: Request, file: UploadFile = File(...)):
    s = _settings(request)
    data = await file.read()
    meta = validate_and_decode(data, s)
    s.storage_dir.mkdir(parents=True, exist_ok=True)
    dest = s.storage_dir / f"{meta['sha256']}{meta['extension']}"
    if not dest.exists():
        dest.write_bytes(data)
    return {"id": meta["sha256"], "format": meta["format"], "width": meta["width"], "height": meta["height"],
            "size_bytes": meta["size_bytes"], "sha256": meta["sha256"]}

@router.get("/uploads/{upload_id}")
def get_upload(request: Request, upload_id: str):
    s = _settings(request)
