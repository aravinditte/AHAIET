@router.post("/process")
def process(request: Request, body: ProcessRequest):
    """AHAIET-009: asynchronous job submission. The queued job is
    persisted and committed BEFORE any work runs; the response is 202
    with the job id, and the bounded background executor drives the
    state machine (see app.services.job_runner). Poll
    GET /api/jobs/{id} and GET /api/jobs/{id}/result; cancel with
    POST /api/jobs/{id}/cancel."""
    s = _settings(request)
    path = _find_upload(s, body.upload_id)
    manager = _manager(request)
    job_id = uuid.uuid4().hex
    job_runner.create_job(s, manager, job_id, body.upload_id, body.language_profile)
    try:
        manager.submit(job_id, lambda: job_runner.run_process_job(
            s, manager, job_id, path, body.model_dump()))
    except job_runner.QueueFullError as e:
        job_runner.update_job(s, manager, job_id, status="failed", stage="queued",
                              error=f"{e.code}: {e.message}")
        resp = JSONResponse(status_code=503, content={
            "error": {"code": e.code, "message": e.message, "detail": e.detail},
            "retry_after_s": e.retry_after_s})
        resp.headers["Retry-After"] = str(e.retry_after_s)
        return resp
    return JSONResponse(status_code=202, content={
        "job_id": job_id, "status": "queued", "stage": "queued", "error": None,
        "stage_timings_ms": {}})

def _job_or_404(request: Request, job_id: str) -> dict:
    view = job_runner.get_job(_settings(request), _manager(request), job_id)
    if view is None:
        raise AppError(404, "job_not_found", f"No job with id '{job_id}'.")
    return view

@router.get("/jobs/{job_id}")
def get_job(request: Request, job_id: str):
    view = _job_or_404(request, job_id)
    view = {k: v for k, v in view.items() if k != "result"}
    return view

@router.get("/jobs/{job_id}/result")
def get_job_result(request: Request, job_id: str):
    view = _job_or_404(request, job_id)
    return {"job_id": job_id, "status": view["status"], "stage": view["stage"],
            "error": view["error"], "result": view.get("result"),
            "stage_timings_ms": view.get("stage_timings_ms", {})}

@router.post("/jobs/{job_id}/cancel")
def cancel_job(request: Request, job_id: str):
    """Best-effort cooperative cancellation (AHAIET-009): the request
    is recorded and honoured between job stages; a decoder subprocess
    already running is not killed."""
    s = _settings(request)
    view = job_runner.request_cancel(s, _manager(request), job_id)
    if view is None:
        raise AppError(404, "job_not_found", f"No job with id '{job_id}'.")
    return {"job_id": job_id, "status": view["status"], "stage": view["stage"],
            "cancel_requested": True}

@router.get("/history")
def history(request: Request):
    _require_access(request)
    s = _settings(request)
    if not s.history_enabled:
        # Explicit disabled state: history recording is off, so there is
        # nothing to list. This is a configuration fact, not an error.
        return {"history": [], "enabled": False, "status": "disabled",
                "reason": "Processing history is disabled by configuration "
                          "(AHAIET_HISTORY_ENABLED=false); no history is recorded."}
    conn = store.connect(s.db_path)
    try:
        rows = [dict(r) for r in conn.execute("SELECT * FROM history ORDER BY id DESC LIMIT 200")]
    finally:
        conn.close()
    return {"history": rows, "enabled": True, "status": "enabled"}

@router.delete("/history/{record_id}")
def delete_history(request: Request, record_id: int):
    s = _settings(request)
    conn = store.connect(s.db_path)
    try:
        cur = conn.execute("DELETE FROM history WHERE id=?", (record_id,)); conn.commit()
        if cur.rowcount == 0:
            raise AppError(404, "history_not_found", f"No history record {record_id}.")
    finally:
        conn.close()
    return {"deleted": record_id}
