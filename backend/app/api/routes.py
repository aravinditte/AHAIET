@router.post("/uploads")
async def upload(request: Request, file: UploadFile = File(...)):
    s = _settings(request)
    data = await file.read()
    meta = validate_and_decode(data, s)
    s.storage_dir.mkdir(parents=True, exist_ok=True)
    dest = s.storage_dir / f"{meta['sha256']}{meta['extension']}"
    if not dest.exists():
        dest.write_bytes(data)
    return {"id": meta["sha256"], "format": meta["format"], "width": meta["width"], "height": meta["height"],
            "size_bytes": meta["size_bytes"], "sha256": meta["sha256"]}

@router.get("/uploads/{upload_id}")
def get_upload(request: Request, upload_id: str):
    s = _settings(request)
    path = _find_upload(s, upload_id)
    ext = path.suffix.lower()
    fmt = {".png": "PNG", ".jpg": "JPEG", ".tiff": "TIFF", ".webp": "WEBP", ".bmp": "BMP"}.get(ext, "PNG")
    return FileResponse(path, media_type=MEDIA[fmt])

@router.post("/ocr")
def ocr(request: Request, body: OcrRequest):
    s = _settings(request)
    path = _find_upload(s, body.upload_id)
    start = time.time()
    text = run_ocr(path, s, body.language_profile)
    return {"request_id": uuid.uuid4().hex, "status": "completed", "original_ocr_text": text,
            "language": suggest_language(text, body.language_profile),
            "processing_time_ms": int((time.time() - start) * 1000)}

@router.post("/translate")
def translate(request: Request, body: TranslateRequest):
    s = _settings(request)
    text = (body.corrected_source_text if body.corrected_source_text is not None else body.text) or ""
    if not text.strip():
        raise ValidationAppError("empty_text", "Source text is empty; there is nothing to translate.")
    start = time.time()
    result = do_translate(text, s, body.source_language)
    sug = suggest_language(text, body.source_language)
    resp = TranslationResponse(
        request_id=uuid.uuid4().hex, status="completed",
        detected_language=sug["suggestion"], selected_language=body.source_language, script="Hebrew",
        original_ocr_text=body.text, corrected_source_text=text,
        english_translation=result["english_translation"], translation_method=result["translation_method"],
        warnings=sug["warnings"], model_versions={"translation": result["model"].get("id")},
        processing_time_ms=int((time.time() - start) * 1000))
    return resp.model_dump()

@router.post("/process")
def process(request: Request, body: ProcessRequest):
    s = _settings(request)
    path = _find_upload(s, body.upload_id)
    job_id = uuid.uuid4().hex
    conn = store.connect(s.db_path)
    try:
        conn.execute("INSERT INTO jobs(id,upload_id,language_profile,status,stage) VALUES (?,?,?,?,?)",
                     (job_id, body.upload_id, body.language_profile, "running", "ocr"))
        conn.commit()
        try:
            text = run_ocr(path, s, body.language_profile)
            status, stage, error, result = "awaiting_translation", "ocr_complete", None, {"original_ocr_text": text}
        except AppError as e:
            status, stage, error, result = "failed", "ocr", f"{e.code}: {e.message} {e.detail or ''}".strip(), None
        conn.execute("UPDATE jobs SET status=?,stage=?,error=?,result_json=?,updated_at=datetime('now') WHERE id=?",
                     (status, stage, error, json.dumps(result) if result else None, job_id))
        conn.execute("INSERT INTO history(upload_id,language_profile,status,detail) VALUES (?,?,?,?)",
                     (body.upload_id, body.language_profile, status, error))
        conn.commit()
    finally:
        conn.close()
    return {"job_id": job_id, "status": status, "stage": stage, "error": error}

def _job_or_404(s: Settings, job_id: str) -> dict:
    conn = store.connect(s.db_path)
    try:
        row = conn.execute("SELECT * FROM jobs WHERE id=?", (job_id,)).fetchone()
    finally:
        conn.close()
    if row is None:
        raise AppError(404, "job_not_found", f"No job with id '{job_id}'.")
    return dict(row)

@router.get("/jobs/{job_id}")
def get_job(request: Request, job_id: str):
    row = _job_or_404(_settings(request), job_id)
    row.pop("result_json", None)
    return row

@router.get("/jobs/{job_id}/result")
def get_job_result(request: Request, job_id: str):
    row = _job_or_404(_settings(request), job_id)
    result = json.loads(row["result_json"]) if row.get("result_json") else None
    return {"job_id": job_id, "status": row["status"], "stage": row["stage"], "error": row["error"], "result": result}

@router.get("/history")
def history(request: Request):
    s = _settings(request)
    conn = store.connect(s.db_path)
    try:
        rows = [dict(r) for r in conn.execute("SELECT * FROM history ORDER BY id DESC LIMIT 200")]
    finally:
        conn.close()
    return {"history": rows}

@router.delete("/history/{record_id}")
def delete_history(request: Request, record_id: int):
    s = _settings(request)
    conn = store.connect(s.db_path)
    try:
        cur = conn.execute("DELETE FROM history WHERE id=?", (record_id,)); conn.commit()
        if cur.rowcount == 0:
            raise AppError(404, "history_not_found", f"No history record {record_id}.")
    finally:
        conn.close()
    return {"deleted": record_id}
