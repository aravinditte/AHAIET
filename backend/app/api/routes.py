@router.delete("/history/{record_id}")
def delete_history(request: Request, record_id: int):
    s = _settings(request)
    conn = store.connect(s.db_path)
    try:
        cur = conn.execute("DELETE FROM history WHERE id=?", (record_id,)); conn.commit()
        if cur.rowcount == 0:
            raise AppError(404, "history_not_found", f"No history record {record_id}.")
    finally:
        conn.close()
    return {"deleted": record_id}
