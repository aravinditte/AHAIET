    ext = path.suffix.lower()
    fmt = {".png": "PNG", ".jpg": "JPEG", ".tiff": "TIFF", ".webp": "WEBP", ".bmp": "BMP"}.get(ext, "PNG")
    return FileResponse(path, media_type=MEDIA[fmt])

